#include "oblivion/motion/dynamics.hpp"
#include <algorithm>
#include <cmath>

namespace oblivion {
namespace {
constexpr double kEpsilon=1e-12;
bool finite_state(const DynamicsState& s) noexcept {
 return std::isfinite(s.x_m)&&std::isfinite(s.y_m)&&std::isfinite(s.heading_rad)&&
 std::isfinite(s.forward_speed_mps)&&std::isfinite(s.lateral_speed_mps)&&
 std::isfinite(s.yaw_rate_radps)&&std::isfinite(s.longitudinal_acceleration_mps2)&&
 std::isfinite(s.lateral_acceleration_mps2);
}
}
DifferentialDriveDynamics::DifferentialDriveDynamics(DynamicsParameters p)noexcept:parameters_(p){}
bool DifferentialDriveDynamics::parameters_valid()const noexcept{
 const auto&p=parameters_;
 return std::isfinite(p.mass_kg)&&std::isfinite(p.yaw_inertia_kg_m2)&&
 std::isfinite(p.wheelbase_track_m)&&std::isfinite(p.center_of_mass_height_m)&&
 std::isfinite(p.gravity_mps2)&&std::isfinite(p.friction_coefficient)&&
 std::isfinite(p.rolling_resistance_coefficient)&&std::isfinite(p.linear_drag_coefficient)&&
 std::isfinite(p.angular_damping_n_m_per_radps)&&p.mass_kg>0&&p.yaw_inertia_kg_m2>0&&
 p.wheelbase_track_m>0&&p.center_of_mass_height_m>=0&&p.gravity_mps2>0&&
 p.friction_coefficient>=0&&p.rolling_resistance_coefficient>=0&&
 p.linear_drag_coefficient>=0&&p.angular_damping_n_m_per_radps>=0;
}
const DynamicsParameters& DifferentialDriveDynamics::parameters()const noexcept{return parameters_;}
DynamicsResult DifferentialDriveDynamics::step(const DynamicsState&s,const DynamicsInput&i,double dt)const noexcept{
 DynamicsResult out{};out.state=s;
 if(!parameters_valid()||!finite_state(s)||!std::isfinite(i.left_wheel_force_n)||
    !std::isfinite(i.right_wheel_force_n)||!std::isfinite(i.road_grade_rad)||
    !std::isfinite(i.road_bank_rad)||!std::isfinite(dt)||dt<=0||
    std::abs(i.road_grade_rad)>=1.45||std::abs(i.road_bank_rad)>=1.45)return out;
 const auto&p=parameters_;
 const double mass=p.mass_kg,g=p.gravity_mps2;
 const double normal=mass*g*std::cos(i.road_grade_rad)*std::cos(i.road_bank_rad);
 if(!std::isfinite(normal)||normal<=kEpsilon)return out;
 out.normal_load_n=normal;
 const double requested=i.left_wheel_force_n+i.right_wheel_force_n;
 out.requested_longitudinal_force_n=requested;
 // Banking supplies an inward gravity component. The remaining lateral
 // acceleration must be generated by tire-road friction.
 const double curvature=s.yaw_rate_radps/(std::abs(s.forward_speed_mps)>1e-6?s.forward_speed_mps:
                                          std::copysign(1e-6,s.forward_speed_mps==0?1.0:s.forward_speed_mps));
 const double lateral_kinematic=s.forward_speed_mps*s.yaw_rate_radps;
 const double lateral_gravity=g*std::sin(i.road_bank_rad)*std::cos(i.road_grade_rad);
 const double required_lateral_accel=lateral_kinematic-lateral_gravity;
 out.required_lateral_force_n=mass*required_lateral_accel;
 const double friction_total=p.friction_coefficient*normal;
 const double per_wheel_friction=0.5*p.friction_coefficient*normal;
 const double per_wheel_lateral=0.5*std::abs(out.required_lateral_force_n);
 const double per_wheel_longitudinal=std::sqrt(std::max(0.0,
     per_wheel_friction*per_wheel_friction-per_wheel_lateral*per_wheel_lateral));
 out.available_longitudinal_force_n=2.0*per_wheel_longitudinal;
 const double applied_left=std::clamp(i.left_wheel_force_n,-per_wheel_longitudinal,per_wheel_longitudinal);
 const double applied_right=std::clamp(i.right_wheel_force_n,-per_wheel_longitudinal,per_wheel_longitudinal);
 out.applied_longitudinal_force_n=applied_left+applied_right;
 out.traction_limited=std::abs(applied_left-i.left_wheel_force_n)>1e-9||
                      std::abs(applied_right-i.right_wheel_force_n)>1e-9||
                      std::abs(out.required_lateral_force_n)>friction_total+1e-9;
 out.traction_utilization=friction_total>kEpsilon?
   std::sqrt(out.applied_longitudinal_force_n*out.applied_longitudinal_force_n+
             out.required_lateral_force_n*out.required_lateral_force_n)/friction_total:0.0;
 const double rolling=p.rolling_resistance_coefficient*normal*
                      (std::abs(s.forward_speed_mps)>1e-5?std::copysign(1.0,s.forward_speed_mps):0.0);
 const double drag=p.linear_drag_coefficient*s.forward_speed_mps*std::abs(s.forward_speed_mps);
 const double grade_force=mass*g*std::sin(i.road_grade_rad);
 const double ax=(out.applied_longitudinal_force_n-rolling-drag-grade_force)/mass;
 const double left=applied_left;
 const double right=applied_right;
 const double yaw_torque=0.5*p.wheelbase_track_m*(right-left)-
                         p.angular_damping_n_m_per_radps*s.yaw_rate_radps;
 const double yaw_accel=yaw_torque/p.yaw_inertia_kg_m2;
 const double ay=lateral_kinematic;
 DynamicsState next=s;
 next.forward_speed_mps+=ax*dt;
 next.yaw_rate_radps+=yaw_accel*dt;
 next.lateral_speed_mps=next.forward_speed_mps*std::sin(0.0); // no independent lateral actuator in ideal differential drive
 const double mid_heading=s.heading_rad+0.5*s.yaw_rate_radps*dt;
 next.x_m+=(s.forward_speed_mps*std::cos(mid_heading)-s.lateral_speed_mps*std::sin(mid_heading))*dt;
 next.y_m+=(s.forward_speed_mps*std::sin(mid_heading)+s.lateral_speed_mps*std::cos(mid_heading))*dt;
 next.heading_rad+=0.5*(s.yaw_rate_radps+next.yaw_rate_radps)*dt;
 next.longitudinal_acceleration_mps2=ax;
 next.lateral_acceleration_mps2=ay;
 if(!finite_state(next))return out;
 out.state=next;out.valid=true;
 (void)curvature;
 return out;
}
} // namespace oblivion
